-- PREPARED, NOT APPLIED. Requires explicit authorization from the owner before running against the shared database.
--
-- Server-owned security state. Until now every table had one `for all` owner policy (live names: *_own), so the owner's browser
-- session — or any script/XSS running with it — could write state that only the server should write. This migration:
--   1. approvals + publication_jobs: the browser can no longer forge approvals, self-approve, edit an approved job or write results.
--   2. channel_connections: the browser can no longer create/modify/delete OAuth connections nor read the encrypted token columns.
--   3. generation_spend (new): append-only spend ledger written only by the server; deleting assets no longer lowers counted spend.
--   4. automation_runs: at most one «running» run per automation (database-level, closes the race between cron and a manual click).
-- The service role (server, lib/supabase/admin.ts) bypasses RLS and keeps full access. Every server query is filtered by the
-- authenticated owner.
-- DEPLOY ORDER: 1) code from branch fase1-seguridad deployed WITH SUPABASE_SERVICE_ROLE_KEY in that environment; 2) apply this file.
-- Rollback: supabase/rollback/20261018120000_server_owned_security.down.sql (restores the previous policies and grants; keeps the
-- ledger table and its rows unless the rollback's optional last statement is enabled).
begin;

-- 1. approvals ------------------------------------------------------------
alter table public.approvals enable row level security;
drop policy if exists approvals_own on public.approvals;
drop policy if exists approvals_owner_all on public.approvals;
drop policy if exists approvals_owner_read on public.approvals;
create policy approvals_owner_read on public.approvals for select to authenticated using (owner_id = (select auth.uid()));

-- 1. publication_jobs -----------------------------------------------------
alter table public.publication_jobs enable row level security;
drop policy if exists publication_jobs_own on public.publication_jobs;
drop policy if exists publication_jobs_owner_all on public.publication_jobs;
drop policy if exists publication_jobs_owner_read on public.publication_jobs;
drop policy if exists publication_jobs_owner_insert on public.publication_jobs;
drop policy if exists publication_jobs_owner_update on public.publication_jobs;
drop policy if exists publication_jobs_owner_delete on public.publication_jobs;
create policy publication_jobs_owner_read on public.publication_jobs for select to authenticated using (owner_id = (select auth.uid()));
create policy publication_jobs_owner_insert on public.publication_jobs for insert to authenticated
  with check (owner_id = (select auth.uid()) and status in ('draft', 'awaiting_approval'));
-- Editable while not approved; an approved (not yet publishing) job may only go back to draft or be cancelled.
create policy publication_jobs_owner_update on public.publication_jobs for update to authenticated
  using (owner_id = (select auth.uid()) and status in ('draft', 'awaiting_approval', 'approved'))
  with check (owner_id = (select auth.uid()) and status in ('draft', 'awaiting_approval', 'cancelled'));
create policy publication_jobs_owner_delete on public.publication_jobs for delete to authenticated
  using (owner_id = (select auth.uid()) and status in ('draft', 'awaiting_approval', 'cancelled'));

-- 2. channel_connections ---------------------------------------------------
alter table public.channel_connections enable row level security;
drop policy if exists connections_own on public.channel_connections;
drop policy if exists channel_connections_owner_all on public.channel_connections;
drop policy if exists channel_connections_owner_read on public.channel_connections;
create policy channel_connections_owner_read on public.channel_connections for select to authenticated using (owner_id = (select auth.uid()));
-- Column privileges: the browser reads only non-secret columns; no browser writes at all.
revoke all on public.channel_connections from anon, authenticated;
grant select (id, owner_id, provider, external_account_id, external_account_name, scopes, status, created_at, updated_at)
  on public.channel_connections to authenticated;

-- 3. generation_spend (server-owned spend ledger) -------------------------
create table if not exists public.generation_spend (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete cascade,
  request_id text not null,
  provider text not null,
  model text not null,
  tier text not null,
  estimate_usd numeric(12,4) not null check (estimate_usd >= 0),
  created_at timestamptz not null default now(),
  unique (owner_id, request_id)
);
create index if not exists generation_spend_owner_created_idx on public.generation_spend (owner_id, created_at desc);
alter table public.generation_spend enable row level security;
drop policy if exists generation_spend_owner_read on public.generation_spend;
create policy generation_spend_owner_read on public.generation_spend for select to authenticated using (owner_id = (select auth.uid()));
revoke all on public.generation_spend from anon, authenticated;
grant select on public.generation_spend to authenticated;

-- 4. automation_runs: one running run per automation -------------------------
-- Checked before preparing: 0 rows in status 'running' (18-10-2026). Orphans older than 15 min would be closed first.
update public.automation_runs set status = 'failed', error = coalesce(error, 'Ejecución interrumpida (cerrada al aplicar la migración de seguridad).'), finished_at = coalesce(finished_at, now())
  where status = 'running' and started_at < now() - interval '15 minutes';
create unique index if not exists automation_runs_one_running_idx on public.automation_runs (automation_id) where status = 'running';

commit;
