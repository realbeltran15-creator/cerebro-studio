#!/usr/bin/env python3
"""Builds supabase/schema/baseline_live.sql from the structure-only snapshots in supabase/schema/ (columns, constraints, other)."""
import re, pathlib
S = pathlib.Path(__file__).resolve().parent.parent / 'supabase' / 'schema'
D = {  # defaults observed in Production (table.column -> expression)
 'approvals.status':"'pending'",'assets.license_status':"'unknown'",'assets.provenance':"'{}'::jsonb",'audit_log.metadata':"'{}'::jsonb",
 'automation_runs.status':"'running'",'automation_runs.summary':"'{}'::jsonb",'automations.enabled':'true','automations.schedule':"'daily'",'automations.config':"'{}'::jsonb",
 'campaigns.name':"''",'campaigns.status':"'borrador'",'campaigns.brief':"'{}'::jsonb",'campaigns.notes':"''",
 'channel_connections.scopes':"'{}'::text[]",'channel_connections.status':"'connected'",'channel_connections.token_metadata':"'{}'::jsonb",
 'connector_configs.enabled':'true','connector_configs.priority':'100','connector_configs.config':"'{}'::jsonb",
 'metric_snapshots.observed':"'{}'::jsonb",'metric_snapshots.calculated':"'{}'::jsonb",
 'opportunities.source_platform':"'youtube'",'opportunities.status':"'discovered'",'opportunities.observed_metrics':"'{}'::jsonb",'opportunities.calculated_metrics':"'{}'::jsonb",'opportunities.evidence':"'[]'::jsonb",
 'projects.status':"'draft'",'projects.target_platforms':"'{}'::text[]",'publication_jobs.status':"'draft'",'publication_jobs.payload':"'{}'::jsonb",'publication_jobs.result':"'{}'::jsonb",
 'render_jobs.status':"'draft'",'render_jobs.composition':"'{}'::jsonb",'research_cache.kind':"'topic'",'research_cache.units':'0','research_cache.searches':'0',
 'scenes.duration_ms':'5000','scenes.metadata':"'{}'::jsonb",'scripts.version':'1','scripts.status':"'draft'",'scripts.sections':"'[]'::jsonb",
 'shorts_factory_items.status':"'prepared'",'shorts_factory_items.prepared_on':"((now() at time zone 'utc'))::date",'shorts_factory_items.interest':"'{}'::jsonb",'shorts_factory_items.sources':"'[]'::jsonb",
 'shorts_factory_items.verification':"'{}'::jsonb",'shorts_factory_items.checks':"'[]'::jsonb",'shorts_factory_items.plan':"'{}'::jsonb",'shorts_factory_items.spend':"'{}'::jsonb",
 'storyboards.aspect_ratio':"'16:9'",'storyboards.version':'1','trend_snapshots.platform':"'youtube'",'trend_snapshots.source':"'radar'",
 'vi_generation_jobs.status':"'draft'",'vi_generation_jobs.blocked_reasons':"'{}'::text[]",'vi_generation_jobs.inputs':"'{}'::jsonb",'vi_generation_jobs.cost_reported':'false',
 'vi_identity_versions.status':"'draft'",'vi_identity_versions.traits':"'{}'::jsonb",'vi_identity_versions.reference_asset_ids':"'{}'::uuid[]",
 'vi_personas.status':"'draft'",'vi_personas.bible':"'{}'::jsonb",'vi_personas.budget_eur':'0','vi_personas.spent_eur':'0',
 'vi_quality_reports.checks':"'[]'::jsonb",'vi_quality_reports.overall':"'pending'",'vi_references.approved':'false',
 'vi_scenes.environment':"'{}'::jsonb",'vi_scenes.reference_asset_ids':"'{}'::uuid[]",'vi_voice_profiles.settings':"'{}'::jsonb",'vi_voice_profiles.sample_asset_ids':"'{}'::uuid[]",'vi_voice_profiles.status':"'draft'",
 'vi_wardrobe.category':"'outfit'",'vi_wardrobe.details':"'{}'::jsonb",'vi_wardrobe.reference_asset_ids':"'{}'::uuid[]"}
IDENT = {'metric_snapshots.id':'generated always as identity','audit_log.id':'generated always as identity','generation_spend.id':'generated by default as identity'}
NOW = {'created_at','updated_at','fetched_at','requested_at','started_at'}
out = ['-- GENERATED by scripts/gen-baseline.py from the structure-only snapshots in supabase/schema/. Do not edit by hand.',
       '-- Reconstructs the public schema of Production (tables, defaults, constraints, indexes, functions, triggers, RLS, storage policies).',
       '-- Contains NO data and NO secrets. For a throw-away/local database only; never run against Production.']
for line in (S/'live-columns.txt').read_text().splitlines():
    if line.startswith('#') or not line.strip(): continue
    t, cols = line.split(': ', 1); defs = []
    for c in cols.split(', '):
        m = re.match(r'(\w+) (.+?)( NN)?$', c); n, ty, nn = m.group(1), m.group(2), m.group(3)
        # numeric(10,4) etc. contain a comma: handled below
        defs.append((n, ty, bool(nn)))
    out.append(f'\n-- {t}'); body = []
    i = 0
    cols_fixed = []
    # re-join numeric(a,b) split by the ", " separator
    parts = cols.split(', '); j = 0
    while j < len(parts):
        p = parts[j]
        if re.search(r'numeric\(\d+$', p): p = p + ', ' + parts[j+1]; j += 1
        cols_fixed.append(p); j += 1
    for p in cols_fixed:
        m = re.match(r'(\w+) (.+?)( NN)?$', p); n, ty, nn = m.group(1), m.group(2), m.group(3)
        ty = ty.replace('timestamptz', 'timestamptz')
        d = ''
        key = f'{t}.{n}'
        if key in IDENT: d = ' ' + IDENT[key]
        elif n == 'id' and ty == 'uuid' and t != 'profiles': d = ' default gen_random_uuid()'
        elif key in D: d = f' default {D[key]}'
        elif n in NOW and ty == 'timestamptz' and nn: d = ' default now()'
        body.append(f'  "{n}" {ty}{" not null" if nn else ""}{d}')
    out.append(f'create table public.{t} (\n' + ',\n'.join(body) + '\n);')
    out.append(f'alter table public.{t} enable row level security;')
cons = [l.split('|', 2) for l in (S/'live-constraints.txt').read_text().splitlines() if l and not l.startswith('#')]
order = {'PRIMARY': 0, 'UNIQUE': 1, 'CHECK ': 2, 'FOREIGN': 3}
cons.sort(key=lambda c: order.get(next((k for k in order if c[2].startswith(k)), 'FOREIGN'), 3))
out.append('\n-- constraints (primary keys, uniques, checks, then foreign keys)')
for t, n, d in cons: out.append(f'alter table public.{t} add constraint {n} {d};')
out.append('\n' + (S/'live-other.sql').read_text())
(S/'baseline_live.sql').write_text('\n'.join(out) + '\n')
print('wrote', S/'baseline_live.sql', len(out), 'blocks')
